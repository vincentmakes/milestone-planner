def default_modes(role_key: str) -> dict[str, Mode]:
    """The shipped ``{key: mode}`` rows of a system role (empty for admin / others)."""
    modes: dict[str, Mode] = {}
    for permission in PERMISSIONS:
        mode = permission.defaults.get(role_key)
        if mode is not None:
            modes[permission.key] = mode
    return modes


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_default_role_permissions_sql() -> str:
    """
    One idempotent statement that seeds the system roles and their defaults.

    A data-modifying CTE: the role ``INSERT ... ON CONFLICT (key) DO NOTHING
    RETURNING id, key`` yields only the roles created by this very statement,
    and the default ``role_permissions`` rows are joined onto those. A role
    that already existed (and whose matrix an admin may have edited, rows
    deleted included) is therefore never re-seeded. Plain SQL, no ``DO``
    block and no Python round trip, so the same text runs in every DDL source,
    the migration file and the tenant auto-migration. No ``;`` inside: asyncpg
    executes one statement per call.
    """
    roles = ",\n".join(
        f"        ({_literal(r.key)}, {_literal(r.name)}, {_literal(r.description)}, TRUE, "
        f"{r.sort_order})"
        for r in SYSTEM_ROLES
    )
    defaults = ",\n".join(
        f"      ({_literal(role.key)}, {_literal(key)}, {_literal(mode)})"
        for role in SYSTEM_ROLES
        for key, mode in default_modes(role.key).items()
    )
    return f"""
    WITH new_roles AS (
      INSERT INTO roles (key, name, description, is_system, sort_order)
      VALUES
{roles}
      ON CONFLICT (key) DO NOTHING
      RETURNING id, key
    )
    INSERT INTO role_permissions (role_id, permission, mode)
    SELECT r.id, d.permission, d.mode
    FROM new_roles r JOIN (VALUES
{defaults}
    ) AS d(role_key, permission, mode) ON d.role_key = r.key
    ON CONFLICT (role_id, permission) DO NOTHING"""


def permission_keys_json() -> str:
    """The content of the committed ``shared/permission-keys.json`` (frontend mirror)."""
    data = {
        "keys": sorted(PERMISSION_KEYS),
        "approvable": sorted(APPROVABLE_KEYS),
        "pm_bundle": sorted(PM_BUNDLE),
    }
    return json.dumps(data, indent=2) + "\n"
