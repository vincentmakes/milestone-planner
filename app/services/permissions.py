"""
The permission catalogue: the single source of truth for permission keys.

Every role holds, per key, one mode: ``allow``, ``approval`` (only on the
approvable keys: the requester's own bookings) or nothing (deny, no row).
The ``admin`` system role holds every key in code and has no
``role_permissions`` rows, so it can never be locked out. The shipped defaults
of the ``superuser`` and ``user`` system roles reproduce the behaviour of the
three hard-coded roles before RBAC, so an upgrade changes nothing for an
existing tenant.

Consumers: the role matrix (``GET /api/permissions``), the seed SQL below
(spliced into every DDL source by ``tenant_provisioner``), the gates of the
later RBAC tasks, and the frontend, which mirrors the key spellings from the
committed ``shared/permission-keys.json`` (generated by
``permission_keys_json()``, kept current by tests/test_permissions_catalogue.py).

Evaluation (implemented by the permission resolver, not here)::

    allowed(user, K, project?) = mode(K) == "allow"
        or (K in PM_BUNDLE and mode("projects.manage_as_pm") == "allow"
            and project.pm_id == user.id)

with the admin role short-circuiting to True.

This module must stay import-light (no models, no database): the tenant
provisioner imports it to build the schema.
"""

import json
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Literal

Mode = Literal["allow", "approval"]

ADMIN_ROLE_KEY = "admin"
SYSTEM_ROLE_KEYS: tuple[str, ...] = (ADMIN_ROLE_KEY, "superuser", "user")

_ALLOW: Mode = "allow"


@dataclass(frozen=True)
class Permission:
    """One permission key with its matrix group, label and shipped defaults."""

    key: str
    group: str
    label: str
    description: str
    approvable: bool = False
    # Default mode per editable system role ("superuser" / "user"); a missing
    # role or ``None`` means deny. The admin role is never listed: it holds
    # every key in code.
    defaults: Mapping[str, Mode | None] = field(default_factory=dict)


@dataclass(frozen=True)
class SystemRole:
    """A system role row: seeded on every tenant, never deletable."""

    key: str
    name: str
    description: str
    sort_order: int


